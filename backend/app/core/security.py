import base64
import hashlib
import hmac
import secrets
import struct
import time

from cryptography.fernet import Fernet
from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerificationError
from argon2.profiles import RFC_9106_LOW_MEMORY

from app.core.config import settings


def _mfa_cipher() -> Fernet:
    key = base64.urlsafe_b64encode(hashlib.sha256(settings.SECRET_KEY.encode()).digest())
    return Fernet(key)

# Explicit RFC 9106 low-memory profile: Argon2id, 64 MiB, 3 iterations, 4 lanes.
_password_hasher = PasswordHasher.from_parameters(RFC_9106_LOW_MEMORY)


def get_password_hash(password: str) -> str:
    return _password_hasher.hash(password)


def verify_password(password: str, stored: str) -> bool:
    try:
        if stored.startswith("$argon2"):
            return _password_hasher.verify(stored, password)
        scheme, rounds, salt, expected = stored.split("$")
        # Support only the legacy format generated by this application. Bound work
        # and field sizes so a malformed stored record cannot exhaust resources.
        if scheme != "pbkdf2_sha256" or rounds != "600000" or len(salt) != 32 or len(expected) != 64:
            return False
        bytes.fromhex(salt)
        bytes.fromhex(expected)
        digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), 600_000)
        return hmac.compare_digest(digest.hex(), expected)
    except (InvalidHashError, VerificationError, ValueError, TypeError, AttributeError):
        return False


def password_needs_rehash(stored: str) -> bool:
    return not stored.startswith("$argon2id$") or _password_hasher.check_needs_rehash(stored)


def hash_token(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def encrypt_mfa_secret(secret: str) -> str:
    return encrypt_sensitive_value(secret)


def decrypt_mfa_secret(encrypted: str) -> str:
    return decrypt_sensitive_value(encrypted)


def encrypt_sensitive_value(value: str) -> str:
    return _mfa_cipher().encrypt(value.encode()).decode()


def decrypt_sensitive_value(encrypted: str) -> str:
    return _mfa_cipher().decrypt(encrypted.encode()).decode()


def _broker_token_cipher() -> Fernet:
    key = settings.BROKER_TOKEN_ENCRYPTION_KEY
    if not key:
        raise RuntimeError("BROKER_TOKEN_ENCRYPTION_KEY is required for broker token storage")
    return Fernet(key.encode())


def encrypt_broker_token(token: str) -> str:
    return _broker_token_cipher().encrypt(token.encode()).decode()


def decrypt_broker_token(encrypted: str) -> str:
    return _broker_token_cipher().decrypt(encrypted.encode()).decode()


def generate_totp_secret() -> str:
    return base64.b32encode(secrets.token_bytes(20)).decode().rstrip("=")


def verify_totp(secret: str, code: str, timestamp: int | None = None) -> bool:
    if len(code) != 6 or not code.isdecimal():
        return False
    key = base64.b32decode(secret + "=" * (-len(secret) % 8), casefold=True)
    current = int((timestamp if timestamp is not None else time.time()) // 30)
    for offset in (-1, 0, 1):
        digest = hmac.new(key, struct.pack(">Q", current + offset), hashlib.sha1).digest()
        index = digest[-1] & 0x0F
        value = (struct.unpack(">I", digest[index:index + 4])[0] & 0x7FFFFFFF) % 1_000_000
        if hmac.compare_digest(f"{value:06d}", code):
            return True
    return False
